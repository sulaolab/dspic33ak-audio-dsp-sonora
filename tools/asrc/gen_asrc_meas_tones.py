def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="write the generated C files")
    mode.add_argument("--check", action="store_true", help="fail if the generated files are stale")
    mode.add_argument("--check-legacy", action="store_true",
                      help="fail unless the two pre-existing tone rows reproduce exactly")
    args = parser.parse_args()

    check_geometry()

    if args.check_legacy:
        return check_legacy()

    expected_header = render_header()
    expected_source = render_source()

    if args.write:
        # Match the checkout format (see .gitattributes: * text=auto eol=crlf) so --write
        # does not leave the tree content-clean but diff-dirty.
        HEADER_OUTPUT.write_text(expected_header, encoding="ascii", newline="\r\n")
        SOURCE_OUTPUT.write_text(expected_source, encoding="ascii", newline="\r\n")
        print(f"wrote {HEADER_OUTPUT.relative_to(ROOT)}")
        print(f"wrote {SOURCE_OUTPUT.relative_to(ROOT)}")
        return 0

    if args.check:
        rc = 0
        for path, expected in ((HEADER_OUTPUT, expected_header), (SOURCE_OUTPUT, expected_source)):
            actual = path.read_text(encoding="ascii").replace("\r\n", "\n")
            if actual != expected:
                print(f"ERROR: stale generated file: {path.relative_to(ROOT)}", file=sys.stderr)
                rc = 1
        if rc == 0:
            print("generated MEAS tone tables are up to date")
        return rc

    print_survey()
    return check_legacy()


if __name__ == "__main__":
    raise SystemExit(main())

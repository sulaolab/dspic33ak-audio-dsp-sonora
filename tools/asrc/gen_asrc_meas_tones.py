def check_legacy() -> int:
    bad = 0
    for (row_idx, lvl_idx), want in sorted(LEGACY_PIN.items()):
        name, length, cycles, _fs = ROWS[row_idx]
        got = quantise(length, cycles, LEVELS_DBFS[lvl_idx])[: len(want)]
        if got != want:
            bad += 1
            diff = [(k, g, w) for k, (g, w) in enumerate(zip(got, want)) if g != w]
            print(f"ERROR: row {name} level {LEVELS_DBFS[lvl_idx]} dBFS differs from the "
                  f"shipped table at {diff[:4]}", file=sys.stderr)
    if bad == 0:
        print(f"legacy tables reproduced exactly ({len(LEGACY_PIN)} vectors, "
              f"{LEGACY_ROWS} pre-existing rows)")
    return 1 if bad else 0


def print_survey() -> None:
    print(f"full scale = {FULL_SCALE} (2**23 - 1)")
    print(f"{'row':<9} {'len':>4} {'cyc':>4} {'nom fs':>8} {'tone':>7}   f at 48 kHz / 96 kHz")
    for name, length, cycles, fs_hz in ROWS:
        f48 = 48000 * cycles / length
        f96 = 96000 * cycles / length
        print(f"{name:<9} {length:>4} {cycles:>4} {fs_hz:>8} {tone_hz(length, cycles, fs_hz):>7}"
              f"   {f48:>9.1f} / {f96:>9.1f}")
    print()
    print("Usability, output Nyquist in brackets:")
    print("  96 k -> 48 k [24000]: LOW 2000 ok, HIGH_48 36000 ALIASES, HIGH_96 18000 ok")
    print("  48 k -> 96 k [48000]: LOW 1000 ok, HIGH_48 18000 ok,      HIGH_96  9000 ok")
    print("  96 k -> 16 k  [8000]: LOW 2000 ok, HIGH_* both above Nyquist -> stopband test only")


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="write the generated C files")
    mode.add_argument("--check", action="store_true", help="fail if the generated files are stale")
    mode.add_argument("--check-legacy", action="store_true",
                      help="fail unless the two pre-existing tone rows reproduce exactly")
    args = parser.parse_args()

    check_geometry()

    if args.check_legacy:
        return check_legacy()

    expected_header = render_header()
    expected_source = render_source()

    if args.write:
        # Match the checkout format (see .gitattributes: * text=auto eol=crlf) so --write
        # does not leave the tree content-clean but diff-dirty.
        HEADER_OUTPUT.write_text(expected_header, encoding="ascii", newline="\r\n")
        SOURCE_OUTPUT.write_text(expected_source, encoding="ascii", newline="\r\n")
        print(f"wrote {HEADER_OUTPUT.relative_to(ROOT)}")
        print(f"wrote {SOURCE_OUTPUT.relative_to(ROOT)}")
        return 0

    if args.check:
        rc = 0
        for path, expected in ((HEADER_OUTPUT, expected_header), (SOURCE_OUTPUT, expected_source)):
            actual = path.read_text(encoding="ascii").replace("\r\n", "\n")
            if actual != expected:
                print(f"ERROR: stale generated file: {path.relative_to(ROOT)}", file=sys.stderr)
                rc = 1
        if rc == 0:
            print("generated MEAS tone tables are up to date")
        return rc

    print_survey()
    return check_legacy()


if __name__ == "__main__":
    raise SystemExit(main())

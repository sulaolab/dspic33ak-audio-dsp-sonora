#!/usr/bin/env python3
"""Generate and verify the MEAS clean-tone tables (audio_app_meas_tones.{h,c}).

RECREATED 2026-08-02.  Both generated files carried a `GENERATED by
tools/gen_asrc_meas_tones.py` header line, but no such script existed anywhere in
the project, so the tables were effectively unmaintainable: adding the 96 kHz-source
HF row needed the generator back first.  This is that generator, reconstructed by solving the
existing tables for their quantisation rule and then required to reproduce every
pre-existing sample byte-for-byte (`--check-legacy`).  The output path in the
generated headers is updated to this file's real location.

WHY A TABLE AND NOT A RUNTIME SINE.  audio_app_meas.c's header records it: a
runtime sinf/float-phase/lrintf source measured a ~-109 dB THD+N floor, which
would cap kernel measurement well short of the -120/-123 dB targets.  A
precomputed table advanced once per SOURCE-domain frame has no such floor.

SAMPLE-DOMAIN EXACT, NOT ABSOLUTE-FREQUENCY.  Each table holds `cycles` whole
sine periods over `len` samples, so it is perfectly periodic (no phase-accumulator
truncation, no spectral leakage from a partial cycle) but its frequency follows
the rate it is played at:

    f = fs_source * cycles / len

That is why a 96 kHz leg needs its own HF row.  The 48 kHz HIGH table is 8
samples / 3 cycles = 18 kHz at 48 kHz, but 36 kHz at 96 kHz -- above a 48 kHz
leg's output Nyquist, where it would alias and measure nothing meaningful.  The
96 kHz HF row is the same absolute tone at 2x oversampling: 16 samples /
3 cycles = 18 kHz at 96 kHz.  Both are minimal (gcd(len, cycles) == 1); a longer
table would be redundant, not more accurate.

QUANTISATION.  Solved from the shipped tables and asserted by --check-legacy:

    A       = (2**23 - 1) * 10**(level_dbfs / 20)
    samp[k] = floor( A * sin(2*pi*cycles*k/len) + 0.5 )

Note the full scale is 2**23 - 1, NOT 2**23: with 2**23 the -1 dBFS peak rounds
to 7476355 where the shipped table has 7476354.  Getting this wrong reproduces
most samples and silently differs on the few near a peak.

No third-party dependency (the standard library is enough for exact integers).
"""


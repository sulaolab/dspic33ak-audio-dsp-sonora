/* Read-only twin of the clear above, used by the dispatcher to decide whether a
 * flag is left asserted with no owned CNF bit behind it (spurious / already
 * handled).  Reading a bit alias is a plain byte read, no hazard. */
static bool nora_gpio_event_irq_flag_is_set(unsigned port_index, bool *flag_set)
{
    if (flag_set == 0)
    {
        return false;
    }

    switch (port_index)
    {
#if defined(_CNAIF)
    case NORA_GPIO_PORT_A: *flag_set = (_CNAIF != 0u); return true;
#endif
#if defined(_CNBIF)
    case NORA_GPIO_PORT_B: *flag_set = (_CNBIF != 0u); return true;
#endif
#if defined(_CNCIF)
    case NORA_GPIO_PORT_C: *flag_set = (_CNCIF != 0u); return true;
#endif
#if defined(_CNDIF)
    case NORA_GPIO_PORT_D: *flag_set = (_CNDIF != 0u); return true;
#endif
#if defined(_CNEIF)
    case NORA_GPIO_PORT_E: *flag_set = (_CNEIF != 0u); return true;
#endif
#if defined(_CNFIF)
    case NORA_GPIO_PORT_F: *flag_set = (_CNFIF != 0u); return true;
#endif
#if defined(_CNGIF)
    case NORA_GPIO_PORT_G: *flag_set = (_CNGIF != 0u); return true;
#endif
#if defined(_CNHIF)
    case NORA_GPIO_PORT_H: *flag_set = (_CNHIF != 0u); return true;
#endif
    default: return false;
    }
}


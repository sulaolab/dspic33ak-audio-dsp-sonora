// Definition
//===========================================================

#define NORA_GPIO_EVENT_PORT_COUNT    8u
#define NORA_GPIO_EVENT_PIN_COUNT     16u
#define NORA_GPIO_EVENT_CNCON_CNSTYLE 0x00000800u
#define NORA_GPIO_EVENT_CNCON_ON      0x00008000u

typedef struct
{
    volatile uint32_t *port;
    volatile uint32_t *cncon;
    volatile uint32_t *cnen0;
    volatile uint32_t *cnen1;
    volatile uint32_t *cnf;
} nora_gpio_event_regs_t;

typedef struct
{
    nora_gpio_pin_t            pin;
    nora_gpio_event_edge_t     trigger;
    nora_gpio_event_callback_t callback;
    void                           *user_data;
    bool                            previous_high;
} nora_gpio_event_slot_t;

#define NORA_GPIO_EVENT_PORT_ROW(L) \
    { &PORT##L, &CNCON##L, &CNEN0##L, &CNEN1##L, &CNF##L }
#define NORA_GPIO_EVENT_PORT_NONE \
    { 0, 0, 0, 0, 0 }

/* Availability below is decided by the DFP bit aliases this driver actually
 * writes (_CNxIF / _CNxIE / _CNxIP), not by IFSn/IECn bank numbers. The bank
 * differs per device (CNA..CND sit in IFS3 on AK512, CNE..CNH in IFS9), and
 * encoding that here is exactly the per-device knowledge the alias form removes.
 *
 * The conditions are spelled out rather than generated by a helper macro:
 * producing `defined` through macro expansion is undefined behaviour
 * (-Wexpansion-to-defined).
 *
 * A port whose change-notification registers exist but whose IRQ aliases are
 * missing would silently lose event support, so that combination is a hard
 * error instead of a quiet NORA_GPIO_EVENT_PORT_NONE row. */
#if defined(PORTA) && defined(CNCONA) && defined(CNEN0A) && defined(CNEN1A) && defined(CNFA) \
    && !(defined(_CNAIF) && defined(_CNAIE) && defined(_CNAIP))
#error "PORTA change-notification registers exist but _CNAIF/_CNAIE/_CNAIP are missing from the DFP"
#endif
#if defined(PORTB) && defined(CNCONB) && defined(CNEN0B) && defined(CNEN1B) && defined(CNFB) \
    && !(defined(_CNBIF) && defined(_CNBIE) && defined(_CNBIP))
#error "PORTB change-notification registers exist but _CNBIF/_CNBIE/_CNBIP are missing from the DFP"
#endif
#if defined(PORTC) && defined(CNCONC) && defined(CNEN0C) && defined(CNEN1C) && defined(CNFC) \
    && !(defined(_CNCIF) && defined(_CNCIE) && defined(_CNCIP))
#error "PORTC change-notification registers exist but _CNCIF/_CNCIE/_CNCIP are missing from the DFP"
#endif
#if defined(PORTD) && defined(CNCOND) && defined(CNEN0D) && defined(CNEN1D) && defined(CNFD) \
    && !(defined(_CNDIF) && defined(_CNDIE) && defined(_CNDIP))
#error "PORTD change-notification registers exist but _CNDIF/_CNDIE/_CNDIP are missing from the DFP"
#endif
#if defined(PORTE) && defined(CNCONE) && defined(CNEN0E) && defined(CNEN1E) && defined(CNFE) \
    && !(defined(_CNEIF) && defined(_CNEIE) && defined(_CNEIP))
#error "PORTE change-notification registers exist but _CNEIF/_CNEIE/_CNEIP are missing from the DFP"
#endif
#if defined(PORTF) && defined(CNCONF) && defined(CNEN0F) && defined(CNEN1F) && defined(CNFF) \
    && !(defined(_CNFIF) && defined(_CNFIE) && defined(_CNFIP))
#error "PORTF change-notification registers exist but _CNFIF/_CNFIE/_CNFIP are missing from the DFP"
#endif
#if defined(PORTG) && defined(CNCONG) && defined(CNEN0G) && defined(CNEN1G) && defined(CNFG) \
    && !(defined(_CNGIF) && defined(_CNGIE) && defined(_CNGIP))
#error "PORTG change-notification registers exist but _CNGIF/_CNGIE/_CNGIP are missing from the DFP"
#endif
#if defined(PORTH) && defined(CNCONH) && defined(CNEN0H) && defined(CNEN1H) && defined(CNFH) \
    && !(defined(_CNHIF) && defined(_CNHIE) && defined(_CNHIP))
#error "PORTH change-notification registers exist but _CNHIF/_CNHIE/_CNHIP are missing from the DFP"
#endif


